"""DiagramSet -> Markdown with one fenced mermaid block per page (flowchart, or sequenceDiagram for sagas)."""

from __future__ import annotations

import re

from .model import DiagramSet, Edge, Group, Page

_UNSAFE = re.compile(r"[^A-Za-z0-9_]")

_FLOW_ARROWS = {"async": "-.->", "external": "-.->", "reference": "-.->", "compensate": "-.->",
                "include": "-.->", "use": "-->"}
_SEQ_ARROWS = {"async": "--)", "compensate": "-->>", "external": "-->>"}


def safe_id(item_id: str) -> str:
    """Mermaid node IDs: letters, digits and underscores only."""
    return "n_" + _UNSAFE.sub("_", item_id)


def _text(label: str) -> str:
    return label.replace('"', "'").replace("\n", " ") or " "


def is_sequence(page: Page) -> bool:
    return any(n.shape == "lifeline" for n in page.nodes)


def _flowchart(page: Page) -> list[str]:
    lines = ["flowchart LR"]
    children: dict[str | None, list[str]] = {}
    groups = {g.id: g for g in page.groups}
    for group in page.groups:
        children.setdefault(group.parent if group.parent in groups else None, []).append(f"g:{group.id}")
    for node in page.nodes:
        children.setdefault(node.parent if node.parent in groups else None, []).append(f"n:{node.id}")
    nodes = {n.id: n for n in page.nodes}

    def emit(item: str, indent: str) -> None:
        kind, item_id = item.split(":", 1)
        if kind == "n":
            node = nodes[item_id]
            open_, close = {"ellipse": ("([", "])"), "hexagon": ("{{", "}}"), "cylinder": ("[(", ")]"),
                            "actor": ("[/", "/]")}.get(node.shape, ("[", "]"))
            lines.append(f'{indent}{safe_id(node.id)}{open_}"{_text(node.label)}"{close}')
            return
        group: Group = groups[item_id]
        lines.append(f'{indent}subgraph {safe_id(group.id)}["{_text(group.label)}"]')
        for child in children.get(group.id, []):
            emit(child, indent + "  ")
        lines.append(f"{indent}end")

    for item in children.get(None, []):
        emit(item, "  ")
    for edge in page.edges:
        lines.append("  " + _flow_edge(edge))
    return lines


def _flow_edge(edge: Edge) -> str:
    arrow = _FLOW_ARROWS.get(edge.kind, "-->")
    label = " ".join(p for p in (edge.source_label, edge.label, edge.target_label) if p)
    middle = f'{arrow}|"{_text(label)}"|' if label else arrow
    return f"{safe_id(edge.source)} {middle} {safe_id(edge.target)}"


def _sequence(page: Page) -> list[str]:
    lines = ["sequenceDiagram"]
    for node in page.nodes:
        if node.shape == "lifeline":
            lines.append(f"  participant {safe_id(node.id)} as {_text(node.label)}")
    for edge in page.edges:
        arrow = _SEQ_ARROWS.get(edge.kind, "->>")
        lines.append(f"  {safe_id(edge.source)}{arrow}{safe_id(edge.target)}: {_text(edge.label)}")
    return lines


def render(ds: DiagramSet) -> str:
    out = [f"# {ds.number:02d} {ds.key} diagrams", "",
           f"Generated by sa-diagrams from the design data (source hash `{ds.source_hash[:12]}`). Do not edit.", ""]
    for page in ds.pages:
        body = _sequence(page) if is_sequence(page) else _flowchart(page)
        out += [f"## {page.title}", "", "```mermaid", *body, "```", ""]
        out += [f"- {note}" for note in page.notes]
        if page.notes:
            out.append("")
    return "\n".join(out)
